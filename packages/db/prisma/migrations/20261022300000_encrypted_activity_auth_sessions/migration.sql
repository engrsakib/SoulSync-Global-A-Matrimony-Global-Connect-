-- Encrypted activity/audit payloads, search tokens, auth sessions, extended event enums

ALTER TABLE "user_activity_logs" ALTER COLUMN "title" DROP NOT NULL;
ALTER TABLE "user_activity_logs" ALTER COLUMN "linkPath" DROP NOT NULL;
ALTER TABLE "user_activity_logs" ADD COLUMN IF NOT EXISTS "payloadEnc" JSONB;
ALTER TABLE "user_activity_logs" ADD COLUMN IF NOT EXISTS "searchTokens" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

CREATE INDEX IF NOT EXISTS "user_activity_logs_search_tokens_gin"
  ON "user_activity_logs" USING GIN ("searchTokens");

CREATE INDEX IF NOT EXISTS "user_activity_logs_userId_type_occurredAt_id_idx"
  ON "user_activity_logs" ("userId", "type", "occurredAt", "id");

ALTER TABLE "audit_events" ADD COLUMN IF NOT EXISTS "payloadEnc" JSONB;
ALTER TABLE "audit_events" ADD COLUMN IF NOT EXISTS "searchTokens" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

CREATE INDEX IF NOT EXISTS "audit_events_search_tokens_gin"
  ON "audit_events" USING GIN ("searchTokens");

CREATE TABLE IF NOT EXISTS "auth_sessions" (
  "id" TEXT NOT NULL,
  "tenantId" TEXT NOT NULL,
  "userId" TEXT NOT NULL,
  "refreshTokenHash" TEXT NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "lastSeenAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "expiresAt" TIMESTAMP(3) NOT NULL,
  "revokedAt" TIMESTAMP(3),
  "payloadEnc" JSONB,
  CONSTRAINT "auth_sessions_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "auth_sessions_refreshTokenHash_key"
  ON "auth_sessions"("refreshTokenHash");

CREATE INDEX IF NOT EXISTS "auth_sessions_userId_revokedAt_expiresAt_idx"
  ON "auth_sessions"("userId", "revokedAt", "expiresAt");

CREATE INDEX IF NOT EXISTS "auth_sessions_tenantId_userId_idx"
  ON "auth_sessions"("tenantId", "userId");

ALTER TABLE "auth_sessions"
  ADD CONSTRAINT "auth_sessions_userId_fkey"
  FOREIGN KEY ("userId") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;

